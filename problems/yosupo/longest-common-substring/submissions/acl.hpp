struct Solver {
  string s, t;
  array<int, 4> ans{};

  Solver(const string &s, const string &t) : s(s), t(t) {}

  void run() {
    const int n = int(s.size());
    const string u = s + "$" + t;
    const int N = int(u.size());
    const vector<int> sa = acl_sa::suffix_array(u);
    const vector<int> lcp = acl_sa::lcp_array(u, sa);
    int a = 0, c = 0, len = 0;
    for (int i = 0; i + 1 < N; ++i) {
      int x = sa[i], y = sa[i + 1];
      if (x > y) swap(x, y);
      if (x < n && n < y && len < lcp[i]) len = lcp[i], a = x, c = y - n - 1;
    }
    ans = {a, a + len, c, c + len};
  }

  array<int, 4> answer() const { return ans; }
};
