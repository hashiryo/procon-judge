"""Warshall-Floyd の入力を作る。入力は V W seed の 3 つで、距離行列はハーネスが LCG で組む。

旧 judge の 15 ケースをそのまま seed に割り当てた (edge / small / mid / rand / heavy)。
"""
import sys

CASES = [
    (8, 100, 1), (9, 100, 1), (15, 100, 1),
    (16, 10, 12345), (31, 100, 67890), (64, 1000, 24680),
    (100, 10, 17090863447481117155), (100, 1000, 4386542788665436018), (100, 100000, 13286093576338010251),
    (256, 10, 15551950608844012517), (300, 10000, 16266341416909603150), (256, 100000, 11090409006512424786),
    (512, 1000, 9678277617427176068), (768, 1000, 8231993706339674461), (768, 100000, 2227445585320707458),
]


def main() -> None:
    v, w, seed = CASES[int(sys.argv[1])]
    print(v, w, seed)


if __name__ == "__main__":
    main()
